#!/usr/bin/env node
// Builds docs/generated/api.md from the /** ... */ doc comment directly above
// each router.get(...) or router.post(...) call in src/routes/.
// Run from the project root:
//   node scripts/gen-api-docs.mjs          rewrite docs/generated/api.md
//   node scripts/gen-api-docs.mjs --check  exit 1 if the file is out of date
//
// Doc comment tags, one per line, after the summary:
//   @access <roles>           who may call the route
//   @query <name> <text>      a query parameter
//   @returns <status> <text>  a success response
//   @error <status> <text>    an error response
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROUTES_DIR = 'src/routes';
const OUTPUT = 'docs/generated/api.md';

const HEADER = [
  '<!-- Generated by scripts/gen-api-docs.mjs from the route doc comments in src/routes/. Do not edit this file by hand; change the doc comment and run `node scripts/gen-api-docs.mjs`. -->',
  '',
  '# HTTP API reference',
  '',
  'Routes of the records service, generated from the doc comment on each route',
  'registration. Errors use the shape `{"error": "..."}`.',
  '',
];

// A doc comment followed by a route registration, and any route registration.
const DOCUMENTED = /\/\*\*([\s\S]*?)\*\/\s*router\.(get|post)\('([^']+)'/g;
const REGISTERED = /router\.(get|post)\('([^']+)'/g;

function parseComment(body) {
  const summary = [];
  const tags = [];
  for (const raw of body.split('\n')) {
    const line = raw.replace(/^\s*\* ?/, '').trimEnd();
    const tag = /^@(\w+)\s+(.*)$/.exec(line);
    if (tag) tags.push({ name: tag[1], text: tag[2] });
    else if (!tags.length && line.trim()) summary.push(line.trim());
  }
  return { summary: summary.join(' '), tags };
}

function collect() {
  const routes = [];
  const files = readdirSync(ROUTES_DIR).filter((name) => name.endsWith('.ts')).sort();
  for (const file of files) {
    const source = readFileSync(path.join(ROUTES_DIR, file), 'utf8');
    const documented = new Set();
    for (const match of source.matchAll(DOCUMENTED)) {
      const method = match[2].toUpperCase();
      documented.add(`${method} ${match[3]}`);
      routes.push({ method, path: match[3], ...parseComment(match[1]) });
    }
    for (const match of source.matchAll(REGISTERED)) {
      const key = `${match[1].toUpperCase()} ${match[2]}`;
      if (!documented.has(key)) {
        console.error(`warning: ${key} in ${ROUTES_DIR}/${file} has no doc comment and is left out`);
      }
    }
  }
  return routes;
}

function list(out, title, tags, name) {
  const items = tags.filter((tag) => tag.name === name);
  if (!items.length) return;
  out.push(`${title}:`, '');
  for (const item of items) {
    const [key, ...rest] = item.text.split(/\s+/);
    out.push(`- \`${key}\`: ${rest.join(' ')}`);
  }
  out.push('');
}

function render(routes) {
  const out = [...HEADER];
  for (const route of routes) {
    out.push(`## ${route.method} ${route.path}`, '');
    if (route.summary) out.push(route.summary, '');
    for (const tag of route.tags.filter((entry) => entry.name === 'access')) out.push(`Access: ${tag.text}`, '');
    list(out, 'Query parameters', route.tags, 'query');
    list(out, 'Responses', route.tags, 'returns');
    list(out, 'Errors', route.tags, 'error');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

const text = render(collect());
if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    current = null;
  }
  if (current !== text) {
    console.error(`${OUTPUT} is out of date; run node scripts/gen-api-docs.mjs`);
    process.exitCode = 1;
  } else {
    console.log(`${OUTPUT} is up to date`);
  }
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}`);
}
