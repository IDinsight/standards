"""Render the API reference from module docstrings.

The modules, page title, and output path come from tools/apidoc.json. Each
module is documented in the order of its `__all__`.

Usage:
    python3 tools/apidoc.py           write the reference
    python3 tools/apidoc.py --check   exit 1 if the committed reference differs
"""

import importlib
import inspect
import json
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent
HEADER = "<!-- Generated by tools/apidoc.py from docstrings. Do not edit by hand. -->"


def doc(obj):
    return inspect.getdoc(obj) or "_No description._"


def signature(function):
    params = []
    for param in inspect.signature(function).parameters.values():
        if param.name == "self":
            continue
        if param.default is inspect.Parameter.empty:
            params.append(param.name)
        else:
            params.append(f"{param.name}={param.default!r}")
    return "(" + ", ".join(params) + ")"


def render(config):
    lines = [f"# {config['title']}", "", HEADER, ""]
    for name in config["modules"]:
        module = importlib.import_module(name)
        lines += [f"## `{name}`", "", doc(module), ""]
        for attr in module.__all__:
            obj = getattr(module, attr)
            if inspect.isclass(obj):
                lines += [f"### class `{attr}`", "", doc(obj), ""]
                for member, value in vars(obj).items():
                    if member.startswith("_") or not inspect.isfunction(value):
                        continue
                    lines += [f"#### `{attr}.{member}{signature(value)}`", "", doc(value), ""]
            else:
                lines += [f"### `{attr}{signature(obj)}`", "", doc(obj), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv):
    config = json.loads((TOOLS / "apidoc.json").read_text(encoding="utf-8"))
    sys.path.insert(0, str(ROOT))
    output = ROOT / config["output"]
    text = render(config)
    if argv == ["--check"]:
        current = output.read_text(encoding="utf-8") if output.exists() else None
        if current != text:
            print(f"{config['output']} is out of date; run python3 tools/apidoc.py", file=sys.stderr)
            return 1
        print(f"{config['output']} is up to date")
        return 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    print(f"wrote {config['output']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
